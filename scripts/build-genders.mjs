// Builds renderer/lib/genders-data.js (noun forms → gender, used to colour nouns in the reader)
// from the Wiktionary-derived list at github.com/gambolputty/german-nouns (CC BY-SA).
//   node scripts/build-genders.mjs path/to/nouns.csv
// Compounds are left out when their last part already gives the right gender (Haustür → Tür),
// because the reader resolves unknown nouns by their longest known ending the same way.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolveGender } from '../renderer/lib/genderResolve.js';

const SKIP = /Toponym|Vorname|Nachname|Eigenname|Abkürzung|Buchstabe|Wortverbindung|adjektivische|Straßenname|Symbol/;

function parseLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') (cur += '"'), i++;
      else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') out.push(cur), (cur = '');
    else cur += c;
  }
  out.push(cur);
  return out;
}

const [csv] = process.argv.slice(2);
const lines = readFileSync(csv, 'utf8').split('\n');
const head = parseLine(lines[0]);
const formCols = head.map((h, i) => (/^(nominativ|genitiv|dativ|akkusativ) (singular|plural)/.test(h) ? i : -1)).filter((i) => i >= 0);

// A noun's own base form wins over the same spelling as an inflected form of another noun
// (Haus is "das Haus", not the genitive of "der Hau").
const lemmas = new Map(); // form -> Set of genders as a base form
const inflected = new Map(); // form -> Set of genders as an inflected form
for (const line of lines.slice(1)) {
  if (!line) continue;
  const r = parseLine(line);
  if (!r[1].includes('Substantiv') || SKIP.test(r[1])) continue;
  const genders = new Set(r.slice(2, 7).filter(Boolean));
  if (genders.size !== 1) continue;
  const g = [...genders][0];
  if (!'mfn'.includes(g)) continue;
  const add = (map, f) => {
    if (!f || !/^\p{Lu}[\p{Ll}ß]+$/u.test(f)) return;
    if (!map.has(f)) map.set(f, new Set());
    map.get(f).add(g);
  };
  add(lemmas, r[0]);
  for (const i of formCols) if (r[i] !== r[0]) add(inflected, r[i]);
}

const forms = new Map(); // form -> 'm' | 'f' | 'n' | 'x' (more than one gender)
for (const f of new Set([...lemmas.keys(), ...inflected.keys()])) {
  const genders = lemmas.get(f) ?? inflected.get(f);
  forms.set(f, genders.size === 1 ? [...genders][0] : 'x');
}

// Shortest first, so a compound is checked against the endings kept before it.
const kept = new Map();
for (const f of [...forms.keys()].sort((a, b) => a.length - b.length || (a < b ? -1 : 1))) {
  const g = forms.get(f);
  const viaEnding = resolveGender(kept, f);
  if (viaEnding === g || (g === 'x' && !viaEnding)) continue;
  kept.set(f, g);
}

const byGender = { m: [], f: [], n: [], x: [] };
for (const [f, g] of kept) byGender[g].push(f);
const body = Object.entries(byGender)
  .map(([g, list]) => `  ${g}: ${JSON.stringify(list.sort().join(' '))},`)
  .join('\n');
writeFileSync(
  new URL('../renderer/lib/genders-data.js', import.meta.url),
  `// Generated by scripts/build-genders.mjs from Wiktionary data (CC BY-SA). Do not edit.\nexport default {\n${body}\n};\n`
);
console.log(forms.size, 'forms →', kept.size, 'kept');
